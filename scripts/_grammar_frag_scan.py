# Actually simpler approach: flag sentences that look like noun-phrase slogans
# Pattern from guide: "Open the dictionary form. The boring form. The one in the vocab list."

files = sorted(glob.glob("content/grammar/chapter-*/chapter.json"))
suspects = []

def check_body(path, text, kind):
    if not text: return
    # split on . ! ?
    parts = re.split(r'(?<=[.!?])\s+', text.strip())
    frags = []
    for p in parts:
        p = p.strip()
        if not p: continue
        # skip if contains Bosnian diacritics heavily and short - might be example
        words = re.findall(r"[A-Za-zšđčćžŠĐČĆŽ']+", p)
        if len(words) == 0: continue
        # NP fragment: starts with The/A/An/This/That/Same/Another/No/Not + noun-ish, no verb
        if re.match(r'^(The|A|An|This|That|Same|Another|No|Not|One|Two|Three|Four|Five|Both|Each|Every|Your|My|Our|Their)\b', p) and not VERBS.search(p):
            if p.endswith('.') and len(words) <= 10:
                frags.append(p)
        # Bare parallel slogans without verbs: "Piles, jobs, matching, doing-words, and little words."
        if p.endswith('.') and ',' in p and not VERBS.search(p) and len(words) <= 12:
            frags.append(p)
        # "X versus Y." without verb
        if re.search(r'\bversus\b|\bvs\.?\b', p, re.I) and not VERBS.search(p) and p.endswith('.'):
            frags.append(p)
        # Single capital word / label as sentence: "Vocative." "Aspect." "Vid."
        if re.match(r'^[A-ZŠĐČĆŽ][a-zšđčćž]*\.$', p):
            frags.append(p)
        # "Mid-cup." style hyphenated slogans as prompts? check prompts separately
        if kind in ('try_prompt',) and re.match(r'^[A-Z].*\.\s+[A-Z]', text):
            # multi sentence prompt starting with fragment label
            first = parts[0] if parts else ''
            if first and len(re.findall(r"[A-Za-z']+", first)) <= 3 and not VERBS.search(first):
                frags.append(first)
    if frags:
        suspects.append((path, kind, frags, text[:300]))

for f in files:
    data = json.load(open(f, encoding='utf-8'))
    base = f.replace('\\','/')
    for block in ('whyHere','englishLies','knownLine','pattern','howYouGuess','trick','nerd'):
        obj = data.get(block) or {}
        check_body(f'{base}.{block}.body', obj.get('body'), 'teaching')
    check_body(f'{base}.next.body', (data.get('next') or {}).get('body'), 'teaching')
    check_body(f'{base}.theme', data.get('theme'), 'theme')
    for i, item in enumerate((data.get('try') or {}).get('items') or []):
        check_body(f'{base}.try.items[{i}].prompt', item.get('prompt'), 'try_prompt')
        check_body(f'{base}.try.items[{i}].explanation', item.get('explanation'), 'try_expl')
    for i, q in enumerate((data.get('quiz') or {}).get('questions') or []):
        check_body(f'{base}.quiz.questions[{i}].question', q.get('question'), 'quiz_q')
        check_body(f'{base}.quiz.questions[{i}].explanation', q.get('explanation'), 'quiz_expl')
    for i, item in enumerate((data.get('look') or {}).get('items') or []):
        check_body(f'{base}.look.items[{i}].english', item.get('english'), 'look_en')
    for i, img in enumerate(data.get('images') or []):
        check_body(f'{base}.images[{i}].grammarCaption', img.get('grammarCaption'), 'caption')

print('SUSPECTS', len(suspects))
